export function localizeUiText(value: string): string {
  if (current !== 'id' || !value) return value;
  let localized = value;
  for (const [english, indonesian] of [...idUiPhrases].sort((a, b) => b[0].length - a[0].length)) {
    localized = localized.split(english).join(indonesian);
  }
  return localized;
}

export function getTranslationKeys(): string[] {
  return Object.keys(dict.en).sort();
}

export function hasCompleteTranslationCoverage(): boolean {
  const englishKeys = Object.keys(dict.en).sort();
  const indonesianKeys = Object.keys(dict.id).sort();
  return englishKeys.length === indonesianKeys.length && englishKeys.every((key, index) => key === indonesianKeys[index]);
}

let current: Lang = 'en';

export function setLanguage(lang: Lang): void {
  current = lang === 'id' ? 'id' : 'en';
}

export function getLanguage(): Lang {
  return current;
}

export function t(key: string, vars: Record<string, string> = {}): string {
  let str = (dict[current] && dict[current][key]) || dict.en[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.split(`{${k}}`).join(v);
  }
  return str;
}
